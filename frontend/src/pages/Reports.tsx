import { useState } from 'react';
import { FileBarChart, Download, Calendar, Clock, FileText, Share2, Loader2, Plus, Youtube, Globe, Sparkles } from 'lucide-react';
import AppLayout from '@/components/layout/AppLayout';
import Header from '@/components/layout/Header';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from '@/components/ui/card';
import { Badge } from '@/components/ui/badge';
import { cn } from '@/lib/utils';
import { useReports, Report } from '@/hooks/useReports';
import { toast } from 'sonner';
import { fetchApi } from '@/lib/api';

const reportTemplates = [
  {
    id: '1',
    name: 'Executive Summary',
    description: 'High-level overview for leadership',
    icon: FileBarChart,
  },
  {
    id: '2',
    name: 'Competitive Deep Dive',
    description: 'Detailed analysis of specific competitor',
    icon: FileText,
  },
  {
    id: '3',
    name: 'Market Landscape',
    description: 'Full market positioning analysis',
    icon: FileBarChart,
  },
  {
    id: '4',
    name: 'YouTube Intelligence Report',
    description: 'Channel benchmarks, format mix & gap analysis',
    icon: Youtube,
  },
];

const Reports = () => {
  const { reports = [], isLoading, generateReport } = useReports();
  const [activeFilter, setActiveFilter] = useState<'weekly' | 'monthly' | 'custom' | null>(null);
  const [isGeneratingYtReport, setIsGeneratingYtReport] = useState(false);

  const weeklyCount = reports.filter((r) => r.report_type === 'weekly').length;
  const monthlyCount = reports.filter((r) => r.report_type === 'monthly').length;
  const customCount = reports.filter((r) => r.report_type === 'custom').length;

  const filteredReports = reports.filter((report) => {
    if (!activeFilter) return true;
    return report.report_type === activeFilter;
  });

  const handleGenerateTemplate = async (templateId: string) => {
    if (templateId === '4') {
      try {
        setIsGeneratingYtReport(true);
        const res = await fetchApi('/youtube/reports/generate', { method: 'POST' });
        toast.success(`YouTube Intelligence Report generated for ${res?.competitors_analyzed || 0} channel(s)!`);
      } catch (e: any) {
        toast.error(e.message || 'Failed to generate YouTube report. Add YouTube channels first.');
      } finally {
        setIsGeneratingYtReport(false);
      }
    } else {
      generateReport.mutate({
        name: templateId === '1' ? 'Executive Summary' : templateId === '2' ? 'Competitive Deep Dive' : 'Market Landscape',
        report_type: 'custom',
        description: 'On-demand custom report generated by user.',
        format: 'pdf',
      });
    }
  };

  const downloadReport = (report: any) => {
    toast.success(`Downloading ${report.name}...`);
  };

  return (
    <AppLayout>
      <Header
        title="Reports"
        subtitle="Generate and schedule competitive intelligence reports"
      />
      <div className="p-6 space-y-6">
        {/* Templates Header */}
        <div>
          <h2 className="text-lg font-bold text-foreground mb-1">Report Templates</h2>
          <p className="text-xs text-muted-foreground mb-4">Choose a preset template to compile your market intelligence</p>

          <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-4">
            {reportTemplates.map((template) => {
              const Icon = template.icon;
              const isYt = template.id === '4';
              return (
                <Card key={template.id} className="glass-card border-border/50 hover:border-primary/50 transition-all flex flex-col justify-between">
                  <CardHeader className="p-5 pb-3">
                    <div className={cn("w-10 h-10 rounded-xl flex items-center justify-center mb-3", isYt ? "bg-red-500/10 text-red-500" : "bg-primary/10 text-primary")}>
                      <Icon className="w-5 h-5" />
                    </div>
                    <CardTitle className="text-base font-semibold">{template.name}</CardTitle>
                    <CardDescription className="text-xs">{template.description}</CardDescription>
                  </CardHeader>
                  <CardContent className="p-5 pt-0">
                    <Button
                      size="sm"
                      variant="outline"
                      className="w-full mt-2 gap-2 text-xs"
                      onClick={() => handleGenerateTemplate(template.id)}
                      disabled={isYt ? isGeneratingYtReport : generateReport.isPending}
                    >
                      {(isYt && isGeneratingYtReport) || (!isYt && generateReport.isPending) ? (
                        <>
                          <Loader2 className="w-3.5 h-3.5 animate-spin" />
                          Compiling...
                        </>
                      ) : (
                        <>
                          <Sparkles className="w-3.5 h-3.5 text-primary" />
                          Generate Report
                        </>
                      )}
                    </Button>
                  </CardContent>
                </Card>
              );
            })}
          </div>
        </div>

        {/* Generated Reports History */}
        <div className="space-y-4 pt-4 border-t border-border/40">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
            <div>
              <h2 className="text-lg font-bold text-foreground">Generated Reports</h2>
              <p className="text-xs text-muted-foreground">View and export your intelligence briefs</p>
            </div>
            <div className="flex gap-2">
              <Button
                variant={activeFilter === null ? 'secondary' : 'ghost'}
                size="sm"
                className="text-xs"
                onClick={() => setActiveFilter(null)}
              >
                All ({reports.length})
              </Button>
              <Button
                variant={activeFilter === 'weekly' ? 'secondary' : 'ghost'}
                size="sm"
                className="text-xs"
                onClick={() => setActiveFilter('weekly')}
              >
                Weekly ({weeklyCount})
              </Button>
              <Button
                variant={activeFilter === 'monthly' ? 'secondary' : 'ghost'}
                size="sm"
                className="text-xs"
                onClick={() => setActiveFilter('monthly')}
              >
                Monthly ({monthlyCount})
              </Button>
              <Button
                variant={activeFilter === 'custom' ? 'secondary' : 'ghost'}
                size="sm"
                className="text-xs"
                onClick={() => setActiveFilter('custom')}
              >
                Custom ({customCount})
              </Button>
            </div>
          </div>

          {isLoading ? (
            <div className="glass-card rounded-xl p-8 text-center text-muted-foreground">
              <Loader2 className="w-6 h-6 animate-spin mx-auto mb-2 text-primary" />
              Loading report archive...
            </div>
          ) : filteredReports.length === 0 ? (
            <div className="glass-card rounded-xl p-8 text-center text-muted-foreground">
              <FileBarChart className="w-10 h-10 mx-auto mb-2 opacity-40" />
              <p className="text-sm font-medium mb-1">No reports generated yet</p>
              <p className="text-xs">Generate your first intelligence summary from the templates above.</p>
            </div>
          ) : (
            <div className="space-y-3">
              {filteredReports.map((report) => (
                <div
                  key={report.id}
                  className="glass-card rounded-xl p-4 flex flex-col sm:flex-row sm:items-center justify-between gap-4 border border-border/50 hover:border-primary/40 transition-all"
                >
                  <div className="flex items-center gap-3">
                    <div className="w-10 h-10 rounded-lg bg-secondary/80 flex items-center justify-center text-primary">
                      <FileText className="w-5 h-5" />
                    </div>
                    <div>
                      <h4 className="font-semibold text-sm text-foreground">{report.name}</h4>
                      <div className="flex items-center gap-3 text-xs text-muted-foreground mt-0.5">
                        <span className="flex items-center gap-1">
                          <Calendar className="w-3.5 h-3.5" />
                          {new Date(report.created_at).toLocaleDateString()}
                        </span>
                        <Badge variant="outline" className="text-[10px] uppercase font-mono px-1.5 py-0">
                          {report.format || 'PDF'}
                        </Badge>
                      </div>
                    </div>
                  </div>

                  <div className="flex items-center gap-2 self-end sm:self-auto">
                    <Button size="sm" variant="outline" onClick={() => downloadReport(report)} className="gap-1.5 text-xs">
                      <Download className="w-3.5 h-3.5" />
                      Download
                    </Button>
                  </div>
                </div>
              ))}
            </div>
          )}
        </div>
      </div>
    </AppLayout>
  );
};

export default Reports;
